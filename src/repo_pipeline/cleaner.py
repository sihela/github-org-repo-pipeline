"""
Data Cleaner Module.

An independent post-processing tool that cleans datasets according to
a validator's JSON report.
Features:
- Consumes the JSON report generated by the validator.
- Deduplicates records based on primary key ('keep_first' or 'keep_last').
- Drops or quarantines unrecoverable records flagged with ERROR in the JSON report.
- Retains records containing only INFO (e.g., missing optional fields) or non-fatal WARNINGs.
- Cleans and repairs fixable fields:
  * Trims excess leading/trailing whitespace while preserving all special characters,
    emojis, accents, and symbols.
  * Coerces numeric/boolean strings to expected types when valid.
  * Normalizes empty strings to None for optional fields.
- Re-evaluates repaired records to guarantee that only clean, valid records are retained.
- Preserves full UTF-8 special characters without mangling or double-encoding.
- Generates a detailed cleaning report (text summary and structured readable JSON).
- Exports cleaned and quarantined datasets to JSON and CSV.
- Completely decoupled from the validator: consumes the validator's JSON output.
"""

import argparse
import csv
import json
import logging
import os
import re
import sys
from typing import Any, Dict, List, Optional, Set, Tuple, Union

from repo_pipeline.validator import FieldRule, Severity, ValidationConfig, ValidationIssue, ValidationReport, Validator

logger = logging.getLogger("cleaner")


class CleaningReport:
    """Encapsulates statistics and detailed logs of a cleaning run."""

    def __init__(
        self,
        total_input_records: int,
        cleaned_records_count: int,
        quarantined_records_count: int,
        duplicates_removed_count: int,
        fields_repaired_count: int,
        repair_logs: List[Dict[str, Any]],
        quarantined_details: List[Dict[str, Any]]
    ):
        self.total_input_records = total_input_records
        self.cleaned_records_count = cleaned_records_count
        self.quarantined_records_count = quarantined_records_count
        self.duplicates_removed_count = duplicates_removed_count
        self.fields_repaired_count = fields_repaired_count
        self.repair_logs = repair_logs
        self.quarantined_details = quarantined_details

    def to_dict(self) -> Dict[str, Any]:
        """Convert cleaning report to dictionary."""
        return {
            "summary": {
                "total_input_records": self.total_input_records,
                "cleaned_records_retained": self.cleaned_records_count,
                "quarantined_records": self.quarantined_records_count,
                "duplicates_removed": self.duplicates_removed_count,
                "fields_repaired": self.fields_repaired_count,
            },
            "quarantined_details": self.quarantined_details,
            "repair_logs": self.repair_logs,
        }

    def save_json(self, filepath: str, indent: int = 2) -> None:
        """Save cleaning report to a readable JSON file."""
        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(self.to_dict(), f, indent=indent, ensure_ascii=False)
        logger.info("Cleaning report saved to JSON: %s", filepath)

    def generate_text_report(self) -> str:
        """Generate a clean human-readable text summary of cleaning actions."""
        lines = [
            "=" * 70,
            " DATA CLEANING REPORT",
            "=" * 70,
            f"Total Input Records:         {self.total_input_records:,}",
            f"Cleaned Records Retained:    {self.cleaned_records_count:,} ({self.cleaned_records_count / max(1, self.total_input_records) * 100:.1f}%)",
            f"Quarantined/Dropped Records: {self.quarantined_records_count:,} ({self.quarantined_records_count / max(1, self.total_input_records) * 100:.1f}%)",
            f"Duplicates Removed:          {self.duplicates_removed_count:,}",
            f"Field Values Repaired:       {self.fields_repaired_count:,}",
            "-" * 70,
        ]

        if self.quarantined_details:
            lines.append("Quarantined Records Summary (first 10):")
            for idx, q in enumerate(self.quarantined_details[:10], start=1):
                pk = q.get("record_id", "<unknown>")
                reasons = ", ".join(q.get("reasons", []))
                lines.append(f"  {idx:2d}. Record ID: {pk:<15} Reason(s): {reasons}")
            if len(self.quarantined_details) > 10:
                lines.append(f"  ... and {len(self.quarantined_details) - 10} more quarantined records.")
            lines.append("-" * 70)

        if self.repair_logs:
            lines.append("Sample Repaired Fields (first 10):")
            for idx, r in enumerate(self.repair_logs[:10], start=1):
                pk = r.get("record_id", "<unknown>")
                fld = r.get("field", "<unknown>")
                action = r.get("action", "")
                lines.append(f"  {idx:2d}. Record {pk} [{fld}]: {action}")
            if len(self.repair_logs) > 10:
                lines.append(f"  ... and {len(self.repair_logs) - 10} more field repairs.")

        lines.append("=" * 70)
        return "\n".join(lines)


class DataCleaner:
    """
    Cleans, deduplicates, and sanitizes dataset records.
    Consumes raw records along with the validator's JSON report.
    """

    def __init__(
        self,
        config: Optional[ValidationConfig] = None,
        duplicate_policy: str = "keep_first",
        coerce_types: bool = True,
        trim_strings: bool = True,
        normalize_empty_to_none: bool = True,
    ):
        """
        :param config: ValidationConfig containing schema and rules.
        :param duplicate_policy: 'keep_first' or 'keep_last'.
        :param coerce_types: Whether to safely convert numeric/boolean strings if type expected.
        :param trim_strings: Strip leading/trailing whitespace while preserving special characters.
        :param normalize_empty_to_none: If an optional field is empty string, set it to None.
        """
        self.config = config or ValidationConfig()
        self.duplicate_policy = duplicate_policy
        self.coerce_types = coerce_types
        self.trim_strings = trim_strings
        self.normalize_empty_to_none = normalize_empty_to_none
        self.validator = Validator(self.config)

    @staticmethod
    def load_validation_report_json(filepath: str) -> Dict[str, Any]:
        """Load an existing validation report JSON file."""
        with open(filepath, "r", encoding="utf-8") as f:
            return json.load(f)

    def _attempt_type_coercion(self, val: Any, expected_type: Any) -> Tuple[Any, bool]:
        """
        Safely coerce string representation to expected types (int, float, bool).
        Returns (coerced_value, did_coerce).
        """
        if val is None:
            return None, False

        # If already matching, no change needed
        if expected_type is int and isinstance(val, int) and not isinstance(val, bool):
            return val, False
        if expected_type is float and isinstance(val, (int, float)) and not isinstance(val, bool):
            return float(val), False
        if expected_type is bool and isinstance(val, bool):
            return val, False

        if isinstance(val, str):
            clean_str = val.strip()
            # Try integer coercion
            if expected_type is int or (isinstance(expected_type, tuple) and int in expected_type):
                if re.match(r"^-?\d+$", clean_str):
                    try:
                        return int(clean_str), True
                    except ValueError:
                        pass

            # Try float coercion
            if expected_type is float or (isinstance(expected_type, tuple) and float in expected_type):
                try:
                    return float(clean_str), True
                except ValueError:
                    pass

            # Try boolean coercion
            if expected_type is bool or (isinstance(expected_type, tuple) and bool in expected_type):
                if clean_str.lower() in ("true", "1", "yes"):
                    return True, True
                if clean_str.lower() in ("false", "0", "no"):
                    return False, True

        return val, False

    def clean_record_fields(
        self, record: Dict[str, Any], record_id: Any
    ) -> Tuple[Dict[str, Any], List[Dict[str, Any]]]:
        """
        Sanitize and repair individual fields of a record.
        Preserves all special characters (accents, emojis, symbols, quotes).
        """
        cleaned = dict(record)
        repair_logs: List[Dict[str, Any]] = []

        for field_name, rule in self.config.field_rules.items():
            if field_name not in cleaned:
                continue

            val = cleaned[field_name]

            # 1. Whitespace trimming for strings (preserving internal special characters)
            if isinstance(val, str) and self.trim_strings:
                stripped = val.strip()
                if stripped != val:
                    cleaned[field_name] = stripped
                    repair_logs.append({
                        "record_id": str(record_id),
                        "field": field_name,
                        "action": "Trimmed leading/trailing whitespace",
                        "original_value": val,
                        "cleaned_value": stripped,
                    })
                    val = stripped

            # 2. Normalize empty strings for optional fields to None
            if isinstance(val, str) and val == "" and not rule.required and self.normalize_empty_to_none:
                cleaned[field_name] = None
                repair_logs.append({
                    "record_id": str(record_id),
                    "field": field_name,
                    "action": "Normalized empty string to None for optional field",
                    "original_value": "",
                    "cleaned_value": None,
                })
                val = None

            # 3. Type Coercion (if configured)
            if self.coerce_types and rule.expected_type is not None and val is not None:
                coerced_val, did_coerce = self._attempt_type_coercion(val, rule.expected_type)
                if did_coerce:
                    cleaned[field_name] = coerced_val
                    repair_logs.append({
                        "record_id": str(record_id),
                        "field": field_name,
                        "action": f"Coerced type from {type(val).__name__} to {type(coerced_val).__name__}",
                        "original_value": val,
                        "cleaned_value": coerced_val,
                    })

        return cleaned, repair_logs

    def clean(
        self,
        records: List[Dict[str, Any]],
        validation_report: Optional[Union[ValidationReport, Dict[str, Any], str]] = None
    ) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]], CleaningReport]:
        """
        Clean dataset records based on validation report.
        :param records: List of record dictionaries.
        :param validation_report: Can be a ValidationReport instance, a report dict, or filepath to JSON.
        :return: (cleaned_records, quarantined_records, cleaning_report)
        """
        pk_field = self.config.primary_key

        # If a JSON filepath is given, load it
        report_dict: Optional[Dict[str, Any]] = None
        if isinstance(validation_report, str):
            report_dict = self.load_validation_report_json(validation_report)
        elif isinstance(validation_report, dict):
            report_dict = validation_report
        elif isinstance(validation_report, ValidationReport):
            report_dict = validation_report.to_dict()

        # If no report was provided, perform initial validation
        if report_dict is None:
            v_report = self.validator.validate(records)
            report_dict = v_report.to_dict()

        cleaned_records: List[Dict[str, Any]] = []
        quarantined_records: List[Dict[str, Any]] = []
        all_repair_logs: List[Dict[str, Any]] = []
        quarantined_details: List[Dict[str, Any]] = []

        seen_keys: Set[Any] = set()
        duplicates_removed_count = 0

        # Handle duplicate policy: if keep_last, reverse evaluation order
        records_to_process = list(enumerate(records))
        if self.duplicate_policy == "keep_last":
            records_to_process.reverse()

        for original_index, raw_record in records_to_process:
            rec_pk = raw_record.get(pk_field) if pk_field else f"<index-{original_index}>"

            # Step 1: Duplicate check on primary key
            if pk_field:
                if rec_pk is None or rec_pk == "":
                    quarantined_records.append(raw_record)
                    quarantined_details.append({
                        "record_id": str(rec_pk),
                        "original_index": original_index,
                        "reasons": [f"MISSING_PRIMARY_KEY: Primary key '{pk_field}' is absent or empty."],
                        "record": raw_record,
                    })
                    continue

                if rec_pk in seen_keys:
                    duplicates_removed_count += 1
                    quarantined_records.append(raw_record)
                    quarantined_details.append({
                        "record_id": str(rec_pk),
                        "original_index": original_index,
                        "reasons": [f"DUPLICATE_KEY: Record with primary key '{rec_pk}' is duplicate."],
                        "record": raw_record,
                    })
                    continue

            # Step 2: Attempt field repairs (whitespace, empty optional strings, type coercions)
            cleaned_rec, rep_logs = self.clean_record_fields(raw_record, rec_pk)

            # Step 3: Re-validate the cleaned record to confirm it meets all rules
            test_seen = set()
            post_clean_issues = self.validator.validate_record(cleaned_rec, index=original_index, seen_keys=test_seen)
            error_issues = [i for i in post_clean_issues if i.severity == Severity.ERROR]

            if error_issues:
                # Still contains unrecoverable errors -> Quarantine
                quarantined_records.append(raw_record)
                quarantined_details.append({
                    "record_id": str(rec_pk),
                    "original_index": original_index,
                    "reasons": [f"{i.code}: {i.message}" for i in error_issues],
                    "record": raw_record,
                })
            else:
                # Successfully cleaned or clean from start -> Retain
                if pk_field and rec_pk is not None:
                    seen_keys.add(rec_pk)
                cleaned_records.append(cleaned_rec)
                all_repair_logs.extend(rep_logs)

        # Restore original order if keep_last was used
        if self.duplicate_policy == "keep_last":
            cleaned_records.reverse()

        cleaning_report = CleaningReport(
            total_input_records=len(records),
            cleaned_records_count=len(cleaned_records),
            quarantined_records_count=len(quarantined_records),
            duplicates_removed_count=duplicates_removed_count,
            fields_repaired_count=len(all_repair_logs),
            repair_logs=all_repair_logs,
            quarantined_details=quarantined_details,
        )

        return cleaned_records, quarantined_records, cleaning_report


def export_dataset_json(data: List[Dict[str, Any]], filepath: str, indent: int = 2) -> None:
    """Save records to UTF-8 formatted JSON file preserving special characters."""
    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=indent, ensure_ascii=False)


def export_dataset_csv(data: List[Dict[str, Any]], filepath: str) -> None:
    """Save records to UTF-8 formatted CSV file preserving special characters."""
    if not data:
        with open(filepath, "w", encoding="utf-8") as f:
            f.write("")
        return

    fieldnames = list(data[0].keys())
    with open(filepath, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for row in data:
            row_copy = row.copy()
            for k, v in row_copy.items():
                if isinstance(v, list):
                    row_copy[k] = "; ".join(str(item) for item in v)
            writer.writerow(row_copy)


def load_dataset(filepath: str) -> List[Dict[str, Any]]:
    """Helper to load JSON or CSV dataset for standalone cleaner runs."""
    if filepath.lower().endswith(".csv"):
        records = []
        with open(filepath, "r", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            for row in reader:
                converted = {}
                for k, v in row.items():
                    if v == "":
                        converted[k] = None
                    elif v in ("True", "true"):
                        converted[k] = True
                    elif v in ("False", "false"):
                        converted[k] = False
                    elif k.endswith("_count") or k in ("id", "size_kb", "open_issues_count"):
                        try:
                            converted[k] = int(v)
                        except ValueError:
                            converted[k] = v
                    elif k == "topics" and v:
                        converted[k] = [t.strip() for t in v.split(";")]
                    else:
                        converted[k] = v
                records.append(converted)
        return records
    else:
        with open(filepath, "r", encoding="utf-8") as f:
            return json.load(f)


def parse_cleaner_args() -> argparse.Namespace:
    """Parse CLI arguments for standalone cleaner script."""
    parser = argparse.ArgumentParser(
        description="Clean dataset records according to validator JSON report.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter
    )
    parser.add_argument("--input", "-i", required=True, help="Path to input dataset (JSON or CSV).")
    parser.add_argument("--report", "-r", required=True, help="Path to validator JSON report.")
    parser.add_argument("--output-clean", "-o", default="cleaned_dataset.json", help="Path for cleaned records.")
    parser.add_argument("--output-quarantine", default="quarantined_dataset.json", help="Path for quarantined records.")
    parser.add_argument("--cleaning-log", default="cleaning_report.json", help="Path for cleaning report JSON.")
    parser.add_argument("--duplicate-policy", choices=["keep_first", "keep_last"], default="keep_first")
    return parser.parse_args()


def main() -> None:
    """Standalone CLI entry point for data cleaner."""
    args = parse_cleaner_args()
    logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] [%(name)s] %(message)s")

    from repo_pipeline.sample_data import get_github_repository_validation_config

    logger.info("Loading records from: %s", args.input)
    records = load_dataset(args.input)
    config = get_github_repository_validation_config()

    cleaner = DataCleaner(config=config, duplicate_policy=args.duplicate_policy)
    logger.info("Cleaning records using validator JSON report: %s", args.report)
    cleaned, quarantined, rep = cleaner.clean(records, validation_report=args.report)

    print("\n" + rep.generate_text_report() + "\n")

    if args.output_clean.lower().endswith(".csv"):
        export_dataset_csv(cleaned, args.output_clean)
    else:
        export_dataset_json(cleaned, args.output_clean)
    logger.info("Saved %d clean records to: %s", len(cleaned), args.output_clean)

    if args.output_quarantine.lower().endswith(".csv"):
        export_dataset_csv(quarantined, args.output_quarantine)
    else:
        export_dataset_json(quarantined, args.output_quarantine)
    logger.info("Saved %d quarantined records to: %s", len(quarantined), args.output_quarantine)

    rep.save_json(args.cleaning_log)


if __name__ == "__main__":
    main()
